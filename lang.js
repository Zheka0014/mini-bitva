// Language: ?lang= in the address, then the saved choice, then Steam's language, then the system language.
function detectLang() {
  try {
    const q = new URLSearchParams(location.search).get("lang");
    if (I18N[q]) return q;
  } catch {}
  try {
    const saved = JSON.parse(localStorage.getItem("mini-bitva-v2") || "{}").lang;
    if (I18N[saved]) return saved;
  } catch {}
  const steam = typeof window !== "undefined" && window.native?.steamLanguage;
  if (steam) return /^(russian|ukrainian)$/.test(steam) ? "ru" : "en";
  const list = typeof navigator !== "undefined" ? navigator.languages || [navigator.language] : [];
  for (const l of list) {
    const c = String(l || "")
      .slice(0, 2)
      .toLowerCase();
    if (c) return ["ru", "uk", "be", "kk"].includes(c) ? "ru" : "en";
  }
  return "ru";
}
let LANG = detectLang();
function txt(key, ...args) {
  let v = I18N[LANG][key];
  if (v === undefined) v = I18N.ru[key];
  if (v === undefined) return key;
  return typeof v === "function" ? v(...args) : v;
}
// Static page text is marked with data-i18n (text), data-i18n-html (text with tags), data-i18n-aria and data-i18n-title.
function applyLang() {
  if (typeof document === "undefined") return;
  if (document.documentElement) document.documentElement.lang = LANG;
  document.title = txt("doc.title");
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = txt(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-html]")) el.innerHTML = txt(el.dataset.i18nHtml);
  for (const el of document.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", txt(el.dataset.i18nAria));
  for (const el of document.querySelectorAll("[data-i18n-title]")) el.title = txt(el.dataset.i18nTitle);
  for (const el of document.querySelectorAll("[data-i18n-ph]")) el.placeholder = txt(el.dataset.i18nPh);
}
applyLang();
